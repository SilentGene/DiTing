# merge gene relative abundance table with gene kegg annotation table
def merge_abun_ko(gene_abundance_matrix, ko_merged_tab, output):
    logging.info('Merge abundance table with kegg table')
    abundances = {}
    with open(gene_abundance_matrix, encoding='utf-8') as fi:
        header = fi.readline().rstrip('\n').split('\t')
        if not header or header[0] != 'gene_id':
            raise ValueError('Gene abundance matrix must start with a gene_id column')
        samples = header[1:]
        for line in fi:
            fields = line.rstrip('\n').split('\t')
            if len(fields) != len(samples) + 1:
                raise ValueError('Malformed row in gene abundance matrix')
            abundances[fields[0]] = fields[1:]

    annotations = []
    with open(ko_merged_tab, encoding='utf-8') as fi:
        for line in fi:
            if line.startswith('#') or not line.strip():
                continue
            gene_id, k_number = line.rstrip('\n').split('\t')[0:2]
            annotations.append((gene_id, k_number))

    with open(output, 'w', encoding='utf-8') as fo:
        fo.write('#sample\tk_number\trelative_abundance\tgene_id\n')
        for gene_id, k_number in sorted(annotations):
            gene_abundances = abundances.get(gene_id, ['0'] * len(samples))
            for sample, abundance in zip(samples, gene_abundances):
                fo.write(
                    sample + '\t' + k_number + '\t' + abundance + '\t' + gene_id + '\n'
                )

def build_gene_family(catalogue_faa, ko_merged_txt, output_dir):
    logging.info('Build gene family according to {}'.format(ko_merged_txt))
    from scripts.fasta_io import read_fasta, write_record

    sequences = {record.identifier: record for record in read_fasta(catalogue_faa)}
    families = {}
    with open(ko_merged_txt, encoding='utf-8') as fi:
        for line in fi:
            if line.startswith('#') or not line.strip():
                continue
            gene_id, k_number = line.rstrip('\n').split('\t')[0:2]
            if gene_id in sequences:
                families.setdefault(k_number, []).append(sequences[gene_id])

    for existing in os.listdir(output_dir):
        if existing.endswith('.faa'):
            os.remove(os.path.join(output_dir, existing))
    for k_number, records in sorted(families.items()):
        with open(os.path.join(output_dir, k_number + '.faa'), 'w', encoding='utf-8') as fo:
            for record in records:
                write_record(fo, record)


#produce table of ko abundance among samples
def table_of_ko_abundance_among_samples(ko_abun_txt, output):
    sampleKnumber_to_abundance = {}
    samples = []
    k_numbers = []
    logging.info('Produce table of ko abundance among samples')
    with open(ko_abun_txt) as fi:
        for line in fi:
            line.strip()
            if line.startswith('#'):
                continue
            else:
                sample = line.split('\t')[0]
                k_number = line.split('\t')[1]
                abundance = line.split('\t')[2]
                key = sample + '+' + k_number
                if key in sampleKnumber_to_abundance:
                    sampleKnumber_to_abundance[key] += float(abundance)
                else:
                    sampleKnumber_to_abundance[key] = float(abundance)
                samples.append(sample)
                k_numbers.append(k_number)

    samples2 = list(set(samples))
    samples2.sort()
    # print(samples2)
    k_numbers2 = list(set(k_numbers))
    k_numbers2.sort()
    # print(k_numbers2)
    with open(output, 'w') as fo:
        fo.write('k_number')
    for sample in samples2:
        with open(output, 'a') as fo:
            fo.write('\t' + sample)
    with open(output, 'a') as fo:
        fo.write('\n')
    for k_number in k_numbers2:
        with open(output, 'a') as fo:
            fo.write(k_number)
        for sample in samples2:
            key = sample + '+' + k_number
            if key not in sampleKnumber_to_abundance.keys():
                sampleKnumber_to_abundance[key] = float(0)
            with open(output, 'a') as fo:
                fo.write('\t' + str(sampleKnumber_to_abundance[key]))
        with open(output, 'a') as fo:
            fo.write('\n')

    logging.info('A table of ko abundance among samples was produced to {}'.format(output))

LEGACY_AMOA_KO = 'K10944'  # pmoA-amoA in KOfam releases before the split
SPLIT_AMOA_KO = 'K28504'   # amoA after KEGG split it from pmoA (K10944)
AMMONIA_OXIDATION_PATHWAY = 'Nitrification, ammonia -> hydroxylamine'


def detect_amoa_ko(ko_list):
    """Return the KO representing amoA in the user's KOfam release.

    KOfam ships no version field, so detect the split directly: newer
    releases define K28504 (amoA) and keep K10944 for pmoA only.
    """
    opener = gzip.open if str(ko_list).endswith('.gz') else open
    with opener(ko_list, 'rt', encoding='utf-8') as fi:
        for line in fi:
            if line.split('\t', 1)[0] == SPLIT_AMOA_KO:
                return SPLIT_AMOA_KO
    return LEGACY_AMOA_KO


def hierarchical_ko_abundance_among_samples(table_of_ko_abundance_among_samples, KO_affilated_to_biogeochemical_cycle_tab, output, amoa_ko=LEGACY_AMOA_KO):
    Knumber_to_abundance = {}
    with open(table_of_ko_abundance_among_samples) as fi:
        for line in fi:
            line = line.rstrip()
            lines = line.split('\t')
            k_number = lines[0]
            lines.pop(0)
            value = '\t'.join(lines)
            Knumber_to_abundance[k_number] = value
    with open(output, 'w') as fo:
        fo.write('')
    amoa_ko_line = SPLIT_AMOA_KO + '\tamoA; ammonia monooxygenase subunit A [EC:1.14.99.39]'
    current_pathway = ''
    with open(KO_affilated_to_biogeochemical_cycle_tab) as fi:
        for line in fi:
            line = line.rstrip()
            fields = line.split('\t')
            if fields[1]:
                current_pathway = fields[1].strip('"')
            # With a post-split KOfam release, amoA is K28504 rather than
            # K10944 (now pmoA only) in the ammonia-oxidation step.
            if (amoa_ko == SPLIT_AMOA_KO
                    and current_pathway.startswith(AMMONIA_OXIDATION_PATHWAY)
                    and fields[2] == LEGACY_AMOA_KO):
                line = '\t'.join(fields[:2]) + '\t' + amoa_ko_line
            k_number = line.split('\t')[2]
            if k_number not in Knumber_to_abundance.keys():
                with open(output, 'a') as fo:
                    fo.write(line + '\n')
            else:
                with open(output, 'a') as fo:
                    fo.write(line + '\t' + str(Knumber_to_abundance[k_number]) + '\n')


